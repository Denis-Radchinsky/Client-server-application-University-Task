CITIES_NORMALIZED = {c.lower().replace("ё", "е"): c for c in CITIES}


def normalize(s):
    return s.strip().lower().replace("ё", "е")


def get_required_letter(city):
    n = normalize(city)
    last = n[-1]
    if last in ("ь", "ъ"):
        return n[-2]
    return last


def find_city(user_input):
    return CITIES_NORMALIZED.get(normalize(user_input))


def play():
    print("=" * 40)
    print("       ИГРА 'ГОРОДА' (Локальная)")
    print("=" * 40)

    n = 0
    while n < 2 or n > 5:
        try:
            n = int(input("Количество игроков (2-5): "))
        except ValueError:
            pass

    players = []
    for i in range(n):
        name = input(f"Имя игрока {i + 1}: ").strip()
        players.append(name)

    random.shuffle(players)
    print(f"\nПорядок хода: {' → '.join(players)}")
    print("Игра началась! Первый игрок называет любой город.")
    print("Введите 'сдаться' чтобы выбыть.\n")

    used = set()
    last_city = None
    active = list(players)

    while len(active) > 1:
        current = active[0]

        if last_city:
            req = get_required_letter(last_city)
            print(f"Последний город: {last_city}  |  Нужна буква: '{req.upper()}'")
            prompt = f"{current} >>> "
        else:
            prompt = f"{current} (любой город) >>> "

        city_input = input(prompt).strip()

        if city_input.lower() == "сдаться":
            print(f"  {current} сдаётся и выбывает.\n")
            active.pop(0)
            continue

        city = find_city(city_input)

        if city is None:
            print(f"  ✗ Города '{city_input}' нет в списке. {current} выбывает.\n")
            active.pop(0)
        elif city in used:
            print(f"  ✗ Город '{city}' уже был назван. {current} выбывает.\n")
            active.pop(0)
        elif last_city and city[0].lower().replace("ё", "е") != get_required_letter(last_city):
            req = get_required_letter(last_city)
            print(f"  ✗ Нужен город на '{req.upper()}'. {current} выбывает.\n")
            active.pop(0)
        else:
            used.add(city)
            last_city = city
            next_letter = get_required_letter(city)
            print(f"  ✓ {city}  (следующий город на '{next_letter.upper()}')\n")
            active.append(active.pop(0))

    print("=" * 40)
    print(f"  ПОБЕДИТЕЛЬ: {active[0]}!")
    print("=" * 40)


if __name__ == "__main__":
    play()
